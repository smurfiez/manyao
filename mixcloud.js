function getSilentWavURI(durationSec = 2, sampleRate = 8000) {
  if (silentWavDataURI) return silentWavDataURI;
  try {
    const numSamples = durationSec * sampleRate;
    const buffer = new ArrayBuffer(44 + numSamples);
    const view = new DataView(buffer);
    function writeString(offset, str) {
      for (let i = 0; i < str.length; i++) view.setUint8(offset + i, str.charCodeAt(i));
    }
    writeString(0, 'RIFF');
    view.setUint32(4, 36 + numSamples, true);
    writeString(8, 'WAVE');
    writeString(12, 'fmt ');
    view.setUint32(16, 16, true);
    view.setUint16(20, 1, true); // PCM
    view.setUint16(22, 1, true); // Mono
    view.setUint32(24, sampleRate, true);
    view.setUint32(28, sampleRate, true);
    view.setUint16(32, 1, true);
    view.setUint16(34, 8, true); // 8-bit PCM
    writeString(36, 'data');
    view.setUint32(40, numSamples, true);
    const bytes = new Uint8Array(buffer);
    bytes.fill(0x80, 44);
    let binary = '';
    for (let i = 0; i < bytes.length; i++) binary += String.fromCharCode(bytes[i]);
    silentWavDataURI = 'data:audio/wav;base64,' + btoa(binary);
    return silentWavDataURI;
  } catch (err) {
    console.warn('Failed to build silent WAV data URI:', err);
    return '';
  }
}

function initAudioSession() {
  if (typeof navigator !== 'undefined' && navigator.audioSession) {
    try {
      navigator.audioSession.type = 'playback';
    } catch (err) {
      console.debug('navigator.audioSession setup:', err);
    }
  }
}

function startAudioAnchor() {
  initAudioSession();
  const anchor = $('#bg-audio-anchor');
  if (!anchor) return;
  if (!anchor.src) {
    const uri = getSilentWavURI();
    if (uri) anchor.src = uri;
  }
  anchor.volume = 0.01;
  const playPromise = anchor.play();
  if (playPromise !== undefined) {
    playPromise.catch((err) => {
      console.debug('Audio anchor play deferred/handled:', err);
    });
  }
}

function stopAudioAnchor() {
  const anchor = $('#bg-audio-anchor');
  if (anchor && !anchor.paused) {
    anchor.pause();
  }
}

function setupBackgroundLifecycle() {
  const unlockAudio = () => {
    initAudioSession();
    window.removeEventListener('pointerdown', unlockAudio);
    window.removeEventListener('touchstart', unlockAudio);
  };
  window.addEventListener('pointerdown', unlockAudio, { passive: true });
  window.addEventListener('touchstart', unlockAudio, { passive: true });

  document.addEventListener('visibilitychange', () => {
    if (document.visibilityState === 'hidden') {
      if (isPlaying && !userExplicitlyPaused) {
        startAudioAnchor();
        if ('mediaSession' in navigator) {
          navigator.mediaSession.playbackState = 'playing';
        }
      }
    } else if (document.visibilityState === 'visible') {
      if (isPlaying && !userExplicitlyPaused) {
        if (widget && typeof widget.getIsPaused === 'function') {
          widget.getIsPaused().then((paused) => {
            if (paused && !userExplicitlyPaused) {
              widget.play();
            }
          }).catch(() => {});
        }
        updatePlayPauseBtn();
        highlightCurrent();
      }
    }
  });

  window.addEventListener('pagehide', () => {
    if (isPlaying && !userExplicitlyPaused) {
      startAudioAnchor();
    }
  });
}

function loadPlaylist() {
  const saved = localStorage.getItem('manyao-mc-playlist');
  if (saved) {
    try {
      playlist = JSON.parse(saved);
      if (!Array.isArray(playlist) || playlist.length === 0) {
        playlist = [...DEFAULT_MC_PLAYLIST];
      }
    } catch {
      playlist = [...DEFAULT_MC_PLAYLIST];
    }
  } else {
    playlist = [...DEFAULT_MC_PLAYLIST];
  }

  if (playlist.length > 0) {
    currentIndex = 0;
    renderPlaylist();
    updateNowPlayingUI();
  }
}


// ── Mixcloud Widget Integration ───────────────────────────────
function initMixcloudWidget() {
  const iframe = document.getElementById('mc-widget');
  if (!iframe || typeof Mixcloud === 'undefined' || !Mixcloud.PlayerWidget) {
    setTimeout(initMixcloudWidget, 250);
    return;
  }

  try {
    widget = Mixcloud.PlayerWidget(iframe);

    widget.ready.then(() => {
      console.log('Mixcloud PlayerWidget Ready');

      widget.events.play.on(() => {
        isPlaying = true;
        userExplicitlyPaused = false;
        startAudioAnchor();
        updatePlayPauseBtn();
        updateMediaSession();
        if ('mediaSession' in navigator) {
          navigator.mediaSession.playbackState = 'playing';
        }
        highlightCurrent();
      });

      widget.events.pause.on(() => {
        if (document.hidden && !userExplicitlyPaused) {
          startAudioAnchor();
          if ('mediaSession' in navigator) {
            navigator.mediaSession.playbackState = 'playing';
          }
          setTimeout(() => {
            if (document.hidden && !userExplicitlyPaused && widget) {
              widget.play();
            }
          }, 200);
        } else {
          isPlaying = false;
          stopAudioAnchor();
          updatePlayPauseBtn();
          if ('mediaSession' in navigator) {
            navigator.mediaSession.playbackState = 'paused';
          }
          highlightCurrent();
        }
      });

      widget.events.ended.on(() => {
        handleSongEnd();
      });

      widget.events.progress.on((seconds, duration) => {
        if (isDraggingProgress) return;
        currentDurationSec = duration || currentDurationSec;

        const pct = duration > 0 ? (seconds / duration) * 100 : 0;
        const bar = $('#progress-filled');
        const timeEl = $('#time-current');
        const durEl = $('#time-duration');

        if (bar) bar.style.width = Math.min(100, Math.max(0, pct)) + '%';
        if (timeEl) timeEl.textContent = formatTime(seconds);
        if (durEl) durEl.textContent = formatTime(duration);

        updateMediaSessionPositionState(seconds, duration);
      });
    }).catch((err) => {
      console.warn('Mixcloud ready error:', err);
    });
  } catch (err) {
    console.warn('Mixcloud widget creation error:', err);
  }
}

// ── Playback Controls ─────────────────────────────────────────
function playSong(index) {
  if (index < 0 || index >= playlist.length || !widget) return;

  currentIndex = index;
  localStorage.setItem('manyao-mc-current-index', index);

  userExplicitlyPaused = false;
  initAudioSession();
  startAudioAnchor();

  const song = playlist[index];
  isPlaying = true;

  currentDurationSec = song.duration || 3600;

  // Mixcloud loads by cloudcast key or feed path
  const feedKey = song.key || song.id;
  currentLoadedIndex = index;
  currentLoadedKey = feedKey;

  openWidget();

  widget.load(feedKey, true).then(() => {
    try {
      widget.play();
    } catch (e) {
      console.warn('Mixcloud play error:', e);
    }
  }).catch((err) => {
    console.warn('Mixcloud load error:', err);
  });

  highlightCurrent();
  updateNowPlayingUI();
  updatePlayPauseBtn();
  showNowPlaying();

  const activeEl = $(`.playlist-item[data-index="${index}"]`);
  if (activeEl) {
    activeEl.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
  }
}

function togglePlayPause() {
  if (!widget) return;

  if (playlist.length === 0) return;

  const targetIdx = currentIndex >= 0 ? currentIndex : 0;
  if (currentLoadedIndex !== targetIdx || !currentLoadedKey) {
    playSong(targetIdx);
    return;
  }

  if (isPlaying) {
    userExplicitlyPaused = true;
    widget.pause();
    stopAudioAnchor();
    if ('mediaSession' in navigator) {
      navigator.mediaSession.playbackState = 'paused';
    }
  } else {
    userExplicitlyPaused = false;
    initAudioSession();
    startAudioAnchor();
    widget.play();
    if ('mediaSession' in navigator) {
      navigator.mediaSession.playbackState = 'playing';
    }
  }
}

function playNext() {
  if (playlist.length === 0) return;

  if (shuffleOn) {
    shufflePosition++;
    if (shufflePosition >= shuffleOrder.length) {
      generateShuffleOrder();
      shufflePosition = 0;
    }
    playSong(shuffleOrder[shufflePosition]);
  } else {
    const next = currentIndex + 1;
    if (next >= playlist.length) {
      playSong(0);
    } else {
      playSong(next);
    }
  }
}

function playPrev() {
  if (playlist.length === 0) return;

  if (shuffleOn) {
    shufflePosition--;
    if (shufflePosition < 0) {
      shufflePosition = shuffleOrder.length - 1;
    }
    playSong(shuffleOrder[shufflePosition]);
  } else {
    const prev = currentIndex - 1;
    if (prev < 0) {
      playSong(playlist.length - 1);
    } else {
      playSong(prev);
    }
  }
}

function handleSongEnd() {
  if (repeatMode === 'one') {
    playSong(currentIndex);
  } else {
    playNext();
  }
}

